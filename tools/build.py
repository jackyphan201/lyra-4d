#!/usr/bin/env python3
"""Render every adapter from the single sources in core/, skills/lyra/ and catalog/.

  python3 tools/build.py          write generated files
  python3 tools/build.py --check  exit 1 if a generated file is stale (used by tests)
  python3 tools/build.py --zips   also build dist/web-skills/*.zip for claude.ai / ChatGPT / Gemini uploads
"""
import argparse
import io
import json
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "installer"))
import lyra4d  # noqa: E402

GENERATED_NOTE = "<!-- Generated by tools/build.py from {src}. Edit the source, then rebuild. -->\n"


def skill_map() -> str:
    lock = json.loads((ROOT / "upstream.lock.json").read_text())
    cat = json.loads((ROOT / "catalog" / "catalog.json").read_text())
    locked = {}
    for e in lock["upstreams"]:
        for s in e["skills"]:
            locked[(e["name"], s["name"])] = (e, s)
    seen = set()
    lines = [GENERATED_NOTE.format(src="catalog/catalog.json and upstream.lock.json"),
             "# Skill map", "",
             "Use this when the core's routing lines do not cover the request. Only skills this session actually lists are available.",
             "`user-only`: the host will not let the model invoke it; the user types `/name` (Claude) or `$name` (Codex), or you read its SKILL.md after approval and say it was loaded from file.",
             "Effects other than `none` need the user's confirmation before you invoke the skill.", ""]
    for g in cat["groups"]:
        lines.append(f"## {g['job']}")
        for s in g["skills"]:
            key = (s["repo"], s["name"])
            if key not in locked:
                raise SystemExit(f"catalog lists {key} but the lock has no such skill")
            seen.add(key)
            e, ls = locked[key]
            tag = "user-only" if ls["user_only"] else "model"
            lines.append(f"- `{s['name']}` ({e['name']}, {tag}; effects: {', '.join(s['effects'])}): {s['hint']}")
        lines.append("")
    missing = sorted(set(locked) - seen)
    if missing:
        raise SystemExit(f"catalog.json is missing locked skills: {missing}")
    lines.append("## Overlaps")
    lines += [f"- {o}" for o in cat["overlaps"]]
    lines.append("")
    return "\n".join(lines)


def claude_plugin_files() -> dict:
    cmd = 'python3 "${CLAUDE_PLUGIN_ROOT}/hooks/lyra_hook.py" --host claude --event '
    hooks = {
        "description": "Lyra 4-D: core once per session, a short intake note every turn, a log line when a skill runs.",
        "hooks": {
            "SessionStart": [{"matcher": "startup|resume|clear|compact",
                              "hooks": [{"type": "command", "command": cmd + "session-start", "timeout": 10}]}],
            "UserPromptSubmit": [{"hooks": [{"type": "command", "command": cmd + "prompt", "timeout": 10}]}],
            "PostToolUse": [{"matcher": "Skill", "hooks": [{"type": "command", "command": cmd + "post-tool", "timeout": 10}]}],
        },
    }
    manifest = {
        "name": "lyra-4d",
        "version": lyra4d.VERSION,
        "description": "Lyra 4-D intake layer: decides between answering, one clarifying question, or a confirmed workflow before any skill runs.",
        "author": {"name": "Lyra 4-D contributors"},
        "license": "MIT",
        "keywords": ["intake", "routing", "prompt", "workflow"],
    }
    files = {
        ".claude-plugin/plugin.json": json.dumps(manifest, indent=2) + "\n",
        "hooks/hooks.json": json.dumps(hooks, indent=2) + "\n",
        "hooks/lyra_hook.py": (ROOT / "hooks" / "lyra_hook.py").read_text(),
        "core/LYRA-CORE.md": (ROOT / "core" / "LYRA-CORE.md").read_text(),
        "core/LYRA-TICK.md": (ROOT / "core" / "LYRA-TICK.md").read_text(),
        "LICENSE": (ROOT / "LICENSE").read_text(),
    }
    for p in sorted((ROOT / "skills" / "lyra").iterdir()):
        if p.is_file():
            files[f"skills/lyra/{p.name}"] = p.read_text()
    return files


def project_file() -> str:
    web = (ROOT / "project" / "src" / "web-notes.md").read_text()
    lyra_skill = (ROOT / "skills" / "lyra" / "SKILL.md").read_text()
    # keep only the prompt-optimizer section of the lyra skill for web use
    start = lyra_skill.index("## Prompt optimizer")
    end = lyra_skill.index("## Diagnostics")
    return (GENERATED_NOTE.format(src="core/LYRA-CORE.md, project/src/web-notes.md, skills/lyra/SKILL.md")
            + (ROOT / "core" / "LYRA-CORE.md").read_text().strip() + "\n\n"
            + web.strip() + "\n\n" + lyra_skill[start:end].strip() + "\n")


def expected_files() -> dict:
    out = {"skills/lyra/SKILL-MAP.md": skill_map(),
           "skills/lyra/LYRA-CORE.md": (ROOT / "core" / "LYRA-CORE.md").read_text()}
    # SKILL-MAP must exist before the plugin copies skills/lyra
    tmp_map = out["skills/lyra/SKILL-MAP.md"]
    plugin = claude_plugin_files()
    plugin["skills/lyra/SKILL-MAP.md"] = tmp_map
    plugin["skills/lyra/LYRA-CORE.md"] = out["skills/lyra/LYRA-CORE.md"]
    for rel, text in plugin.items():
        out[f"adapters/claude/lyra-4d/{rel}"] = text
    out["adapters/codex/AGENTS-block.md"] = lyra4d.managed_block()
    out["adapters/gemini/GEMINI-block.md"] = lyra4d.managed_block()
    out["project/LYRA-PROJECT.md"] = project_file()
    out[".claude-plugin/marketplace.json"] = json.dumps({
        "name": "lyra-4d",
        "owner": {"name": "Lyra 4-D"},
        "description": "Lyra 4-D intake layer for Claude Code. Use installer/lyra4d.py to also add the pinned upstream skills.",
        "plugins": [{"name": "lyra-4d", "source": "./adapters/claude/lyra-4d",
                     "description": "Lyra 4-D intake layer (hooks + lyra skill)"}],
    }, indent=2) + "\n"
    return out


def build_zips():
    dist = ROOT / "dist" / "web-skills"
    dist.mkdir(parents=True, exist_ok=True)
    src = ROOT / "skills" / "lyra"
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for p in sorted(src.iterdir()):
            if p.is_file():
                z.write(p, f"lyra/{p.name}")
    (dist / "lyra.zip").write_bytes(buf.getvalue())
    print(f"wrote {dist / 'lyra.zip'}")
    lock = json.loads((ROOT / "upstream.lock.json").read_text())
    for e in lock["upstreams"]:
        st = lyra4d.store_dir() / f"{e['name']}@{e['commit']}"
        if not st.exists():
            print(f"skip upstream zips for {e['name']}: run the installer first so the verified store exists")
            continue
        over = []
        for s in e["skills"]:
            if len(s["description"]) > 200 or len(s["name"]) > 64:
                over.append(f"{s['name']} (description {len(s['description'])} chars)")
            buf = io.BytesIO()
            with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
                for rel in lyra4d.files_under(e, s["dir"]):
                    p = st / rel
                    if p.is_file() and not p.is_symlink():
                        z.write(p, f"{s['name']}/{rel[len(s['dir']) + 1:]}")
                z.writestr(f"{s['name']}/LICENSE-UPSTREAM", (st / "LICENSE").read_text())
            (dist / e["name"]).mkdir(exist_ok=True)
            (dist / e["name"] / f"{s['name']}.zip").write_bytes(buf.getvalue())
        (dist / e["name"] / "LIMITS.txt").write_text(
            "claude.ai custom skills accept a description of at most 200 characters. These upstream skills exceed it "
            "and are left unchanged, so claude.ai may refuse them:\n" + "\n".join(over) + "\n"
            "Gemini app skills take a folder or SKILL.md, not a .zip: unzip first.\n")
        print(f"wrote {dist / e['name']}/*.zip ({len(e['skills'])} skills; {len(over)} over claude.ai limits, see LIMITS.txt)")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--zips", action="store_true")
    a = ap.parse_args()
    stale = []
    for rel, text in expected_files().items():
        p = ROOT / rel
        cur = p.read_text() if p.exists() else None
        if cur != text:
            stale.append(rel)
            if not a.check:
                p.parent.mkdir(parents=True, exist_ok=True)
                p.write_text(text)
                if rel.endswith(".py"):
                    p.chmod(0o755)
    if a.check:
        if stale:
            print("stale generated files:\n  " + "\n  ".join(stale))
            return 1
        print("generated files up to date")
        return 0
    print(f"updated {len(stale)} file(s)" + (": " + ", ".join(stale) if stale else ""))
    if a.zips:
        build_zips()
    return 0


if __name__ == "__main__":
    sys.exit(main())
